test('G4 main as 1.2 reads it: "./x" and "x" are "x.js"; a leading "/" is kept (absolute to Node); a directory move, .cjs or .mjs stays a change', async () => {
  const doc = pk([
    ['1.0.0', 0, { main: 'dist/index.js', bin: { x: 'cli.js' } }],
    ['1.0.1', 10, { main: './/dist/index', bin: { x: './cli.js' } }],
    ['1.0.2', 20, { main: '/dist/index.js', bin: { x: '/cli.js' } }],
    ['1.0.3', 30, { main: '/dist/index', bin: { x: '/cli.js' } }],
    ['1.0.4', 40, { main: '/dist/index.cjs', bin: { x: '/cli.js' } }],
    ['1.0.5', 50, { main: '/dist/', bin: { x: '/cli.js' } }],
  ]);
  const r1 = await run(doc, '1.0.1'); assert.equal(r1.result, 'ALLOW', r1.detail);
  const r2 = await run(doc, '1.0.2'); assert.equal(r2.result, 'WARN'); assert.deepEqual(r2.components, ['bin_changed', 'main'], '"/dist/index.js" is not "dist/index.js"');
  const r3 = await run(doc, '1.0.3'); assert.equal(r3.result, 'ALLOW', '"/dist/index" is "/dist/index.js"');
  const r4 = await run(doc, '1.0.4'); assert.equal(r4.result, 'WARN'); assert.deepEqual(r4.components, ['main']);
  const r5 = await run(doc, '1.0.5'); assert.equal(r5.result, 'WARN'); assert.deepEqual(r5.components, ['main'], '"/dist/" gets no .js');
  const M = await T16();
  assert.equal(M.mainOf({}), 'index.js'); assert.equal(M.mainOf({ main: 'index' }), 'index.js');
  assert.equal(M.mainOf({ main: '/' }), '/'); assert.equal(M.mainOf({ main: '/x' }), '/x.js'); assert.equal(M.mainOf({ main: './/x' }), 'x.js');
});

test('G5 +pipekey1: a prerelease is compared with the previous version of its tag in its line; the first of a tag is not evaluable; a release follows the latest of its line', async () => {
  const doc = pk([
    ['1.0.0', 0, { main: 'index.js' }],
    ['1.1.0-beta.1', 10, { main: 'beta.js' }],
    ['1.1.0-rc.1', 20, { main: 'rc.js' }],
    ['1.1.0-beta.2', 30, { main: 'beta.js' }],
    ['1.1.0', 40, { main: 'index.js' }],
  ]);
  for (const v of ['1.1.0-beta.1', '1.1.0-rc.1']) {
    const r = await run(doc, v);
    assert.equal(r.result, 'SKIP', v); assert.equal(r.detail, 'not evaluable: no earlier prerelease of the same tag in this release line');
  }
  const b2 = await run(doc, '1.1.0-beta.2');
  assert.equal(b2.result, 'ALLOW', 'compared with 1.1.0-beta.1, not the rc published between them');
  assert.equal(b2.detail, 'lifecycle scripts, bin and main as in 1.1.0-beta.1');
  const rel = await run(doc, '1.1.0');
  assert.equal(rel.result, 'WARN'); assert.equal(rel.detail, 'vs 1.1.0-beta.2: main changed');
});

